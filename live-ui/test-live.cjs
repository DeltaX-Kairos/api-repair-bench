const source = 'def normalize_id(value):\n    return int(value)\n';
const contract = {description:'Preserve strings exactly.',checks:[{id:'zero',args:['001'],expected:'001'},{id:'number',args:[1],error:'ValueError'}]};
const good = customPayload(source, JSON.stringify(contract));
assert.deepEqual(good, {source, checks:contract});
assert.throws(()=>customPayload(source,'{oops'), /valid JSON/);
assert.throws(()=>customPayload(source,JSON.stringify({...contract,checks:[...contract.checks,contract.checks[0]]})),/unique/);
assert.throws(()=>customPayload(source,JSON.stringify({...contract,checks:[{id:'x',args:[],expected:null,error:'ValueError'}]})),/either/);
assert.throws(()=>customPayload('é'.repeat(4097),JSON.stringify(contract)),/8 KB/);
assert.throws(()=>customPayload(source,JSON.stringify({...contract,checks:Array.from({length:9},(_,i)=>({id:String(i),args:[],expected:null}))})),/eight/);
assert.equal(customPayload(source,JSON.stringify({...contract,checks:[{id:'null',args:[],expected:null}]})).checks.checks[0].expected,null);

